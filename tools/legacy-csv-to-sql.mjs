import fs from 'node:fs';
import path from 'node:path';

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) {
  args.set(process.argv[i], process.argv[i + 1]);
}

const directorioPath = args.get('--directorio');
const usuariosPath = args.get('--usuarios');
const outPath = args.get('--out') || 'database/imports/legacy_import.sql';

if (!directorioPath && !usuariosPath) {
  console.error('Uso: node tools/legacy-csv-to-sql.mjs --directorio Directorio.csv --usuarios Coord_Academicos.csv --out database/imports/legacy_import.sql');
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let value = '';
  let quoted = false;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    const next = text[i + 1];

    if (quoted) {
      if (char === '"' && next === '"') {
        value += '"';
        i += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        value += char;
      }
      continue;
    }

    if (char === '"') {
      quoted = true;
    } else if (char === ',') {
      row.push(value);
      value = '';
    } else if (char === '\n') {
      row.push(value);
      rows.push(row);
      row = [];
      value = '';
    } else if (char !== '\r') {
      value += char;
    }
  }

  row.push(value);
  rows.push(row);
  return rows.filter((current) => current.some((cell) => cell.trim()));
}

function normalizeHeader(value) {
  return (value || '')
    .toString()
    .trim()
    .toUpperCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^A-Z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeText(value) {
  return (value || '').toString().replace(/\s+/g, ' ').trim();
}

function normalizeUpper(value) {
  return normalizeText(value).toUpperCase();
}

function normalizeComparable(value) {
  return normalizeUpper(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^A-Z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function sql(value) {
  if (value === null || value === undefined || value === '') return 'NULL';
  return `'${value.toString().replace(/'/g, "''")}'`;
}

function textSql(value) {
  return `'${(value ?? '').toString().replace(/'/g, "''")}'`;
}

function tableFromCsv(filePath) {
  const rows = parseCsv(fs.readFileSync(filePath, 'utf8'));
  const headers = rows[0].map(normalizeHeader);
  return rows.slice(1).map((cells, index) => ({
    sourceRow: index + 2,
    get(name) {
      const idx = headers.indexOf(normalizeHeader(name));
      return idx >= 0 ? normalizeText(cells[idx] || '') : '';
    }
  }));
}

function splitName(fullName) {
  const parts = normalizeUpper(fullName).split(/\s+/).filter(Boolean);
  if (parts.length >= 4) {
    return {
      firstNames: parts.slice(0, -2).join(' '),
      paternalLastName: parts.at(-2) || '',
      maternalLastName: parts.at(-1) || ''
    };
  }
  if (parts.length === 3) {
    return {
      firstNames: parts[0],
      paternalLastName: parts[1],
      maternalLastName: parts[2]
    };
  }
  return {
    firstNames: parts[0] || '',
    paternalLastName: parts[1] || '',
    maternalLastName: ''
  };
}

function roleCode(value) {
  const role = normalizeText(value).toLowerCase();
  return ['admin', 'coordinador', 'finanzas', 'contador', 'contabilidad'].includes(role) ? role : 'coordinador';
}

function status(value) {
  return normalizeUpper(value) === 'INACTIVO' ? 'INACTIVO' : 'ACTIVO';
}

function paymentType(value) {
  const type = normalizeUpper(value);
  return ['E', '1', '2'].includes(type) ? type : '';
}

function category(value) {
  const cat = normalizeUpper(value);
  return ['V', 'M', 'N'].includes(cat) ? cat : '';
}

function maybeEmail(value) {
  const email = normalizeText(value).toLowerCase();
  return /^[^\s@]+@tecplayacar\.edu\.mx$/.test(email) ? email : '';
}

const output = [
  '-- Import legacy generated by tools/legacy-csv-to-sql.mjs',
  '-- Review before importing into Cloud SQL.',
  'BEGIN;'
];
const warnings = [];

if (usuariosPath) {
  for (const row of tableFromCsv(usuariosPath)) {
    const email = maybeEmail(row.get('Usuario'));
    const displayName = row.get('Nombre');
    const notes = row.get('Observacion') || row.get('Campus');
    if (!email || !displayName) {
      warnings.push(`Usuario omitido fila ${row.sourceRow}: requiere Usuario con correo @tecplayacar.edu.mx y Nombre.`);
      continue;
    }

    output.push(`
INSERT INTO app_users (email, display_name, role_id, status, notes, legacy_username, legacy_row_number, updated_at)
SELECT ${textSql(email)}, ${textSql(displayName)}, r.id, ${sql(status(row.get('Estatus')))}::user_status, ${textSql(notes)}, ${textSql(row.get('Usuario'))}, ${row.sourceRow}, now()
FROM roles r
WHERE r.code = ${sql(roleCode(row.get('Rol')))}
ON CONFLICT (email) DO UPDATE
SET display_name = EXCLUDED.display_name,
    role_id = EXCLUDED.role_id,
    status = EXCLUDED.status,
    notes = EXCLUDED.notes,
    legacy_username = EXCLUDED.legacy_username,
    legacy_row_number = EXCLUDED.legacy_row_number,
    updated_at = now();`);
  }
}

if (directorioPath) {
  for (const row of tableFromCsv(directorioPath)) {
    const fullName = normalizeUpper(row.get('DOCENTE'));
    const derived = splitName(fullName);
    const firstNames = normalizeUpper(row.get('NOMBRES') || derived.firstNames);
    const paternalLastName = normalizeUpper(row.get('APELLIDO PATERNO') || derived.paternalLastName);
    const maternalLastName = normalizeUpper(row.get('APELLIDO MATERNO') || derived.maternalLastName);
    const finalName = [firstNames, paternalLastName, maternalLastName].filter(Boolean).join(' ');
    const normalizedName = normalizeComparable(row.get('NOMBRE NORMALIZADO') || finalName);

    if (!finalName || !firstNames || !paternalLastName) {
      warnings.push(`Docente omitido fila ${row.sourceRow}: requiere DOCENTE o NOMBRES/APELLIDO PATERNO.`);
      continue;
    }

    const coord = row.get('COORDINADOR');
    const coordSql = coord
      ? `
coord AS (
  INSERT INTO coordinations (name, status)
  VALUES (${textSql(coord)}, 'ACTIVO')
  ON CONFLICT (name) DO UPDATE SET status = 'ACTIVO'
  RETURNING id
),
picked_coord AS (
  SELECT id FROM coord
  UNION
  SELECT id FROM coordinations WHERE name = ${textSql(coord)}
)`
      : 'picked_coord AS (SELECT NULL::uuid AS id)';

    output.push(`
WITH ${coordSql}
INSERT INTO teachers (
  legacy_row_number,
  legacy_teacher_id,
  full_name,
  normalized_name,
  first_names,
  paternal_last_name,
  maternal_last_name,
  degree,
  payment_type,
  category,
  location,
  comment,
  observation,
  coordination_id,
  phone,
  email,
  rfc,
  external_identifier,
  bank_detail,
  status,
  updated_at
)
VALUES (
  ${row.sourceRow},
  ${sql(row.get('ID DOCENTE'))},
  ${textSql(finalName)},
  ${textSql(normalizedName)},
  ${textSql(firstNames)},
  ${textSql(paternalLastName)},
  ${textSql(maternalLastName)},
  ${textSql(row.get('GRADO'))},
  ${textSql(paymentType(row.get('TIPO DE PAGO')))},
  ${textSql(category(row.get('CATEGORIA')))},
  ${textSql(row.get('UBICACION') || 'Local')},
  ${textSql(row.get('COMENTARIO'))},
  ${textSql(row.get('OBSERVACION'))},
  (SELECT id FROM picked_coord LIMIT 1),
  ${textSql(row.get('TELEFONO').replace(/[^0-9+]/g, ''))},
  ${textSql(normalizeText(row.get('CORREO')).toLowerCase())},
  ${textSql(normalizeUpper(row.get('RFC')).replace(/\s+/g, ''))},
  ${textSql(normalizeUpper(row.get('IDENTIFICADOR')))},
  ${textSql(row.get('BANCO DETALLE'))},
  ${sql(status(row.get('ESTATUS')))}::teacher_status,
  now()
)
ON CONFLICT (normalized_name) DO UPDATE
SET legacy_row_number = EXCLUDED.legacy_row_number,
    legacy_teacher_id = EXCLUDED.legacy_teacher_id,
    full_name = EXCLUDED.full_name,
    first_names = EXCLUDED.first_names,
    paternal_last_name = EXCLUDED.paternal_last_name,
    maternal_last_name = EXCLUDED.maternal_last_name,
    degree = EXCLUDED.degree,
    payment_type = EXCLUDED.payment_type,
    category = EXCLUDED.category,
    location = EXCLUDED.location,
    comment = EXCLUDED.comment,
    observation = EXCLUDED.observation,
    coordination_id = EXCLUDED.coordination_id,
    phone = EXCLUDED.phone,
    email = EXCLUDED.email,
    rfc = EXCLUDED.rfc,
    external_identifier = EXCLUDED.external_identifier,
    bank_detail = EXCLUDED.bank_detail,
    status = EXCLUDED.status,
    updated_at = now();`);
  }
}

output.push('COMMIT;', '');

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output.join('\n'), 'utf8');

console.log(`SQL generado: ${outPath}`);
if (warnings.length) {
  console.log('Advertencias:');
  for (const warning of warnings) console.log(`- ${warning}`);
}
